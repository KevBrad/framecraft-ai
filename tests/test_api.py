def test_cancel_drain_guards_delete(client):
    pid, jid = str(uuid4()), str(uuid4())
    with worker.lock, Session.begin() as db:
        directory = worker.project_dir(pid)
        directory.mkdir()
        db.add(Project(id=pid, title='cancel guard', filename='local.mp4', media={'duration': 1}, settings={}))
        db.add(Job(id=jid, project_id=pid, kind='analysis', status='running'))
        worker.active_job_id = jid
    try:
        assert client.post(f'/api/jobs/{jid}/cancel').json()['status'] == 'cancelled'
        assert client.delete(f'/api/projects/{pid}').status_code == 409
        assert directory.exists()
    finally:
        worker.active_job_id = None
    assert client.delete(f'/api/projects/{pid}').status_code == 204
    assert not directory.exists()


def test_missing_model_failure_and_real_retry(client, monkeypatch):
    fixture = ROOT / 'tests' / 'artifacts' / 'jfk-source.mp4'
