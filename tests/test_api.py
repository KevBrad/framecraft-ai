def wait_project(client, pid, kind, timeout=90, expected='complete'):
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        p = client.get(f'/api/projects/{pid}').json()
        jobs = [j for j in p['jobs'] if j['kind'] == kind]
        if jobs and jobs[0]['status'] not in ('queued', 'running'):
            assert jobs[0]['status'] == expected, jobs[0]
            return p
        time.sleep(.25)
    raise AssertionError(f'{kind} did not finish within {timeout}s')


