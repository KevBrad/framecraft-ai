def test_real_speech_edit_render_and_persistence(client):
    fixture = ROOT / 'tests' / 'artifacts' / 'jfk-source.mp4'
    if not fixture.is_file():
        pytest.skip('Run scripts/prepare_fixture.py to acquire the authorized human-speech fixture.')
    response = client.post('/api/projects', data={'rights_confirmed': 'true', 'title': 'Real speech acceptance', 'min_duration': '15', 'max_duration': '45'},
                           files={'file': ('jfk.mp4', fixture.read_bytes(), 'video/mp4')})
    assert response.status_code == 201, response.text
    pid = response.json()['id']
    p = wait_project(client, pid, 'analysis')
    import hashlib
    assert p['provenance']['sha256'] == hashlib.sha256(fixture.read_bytes()).hexdigest()
    assert p['provenance']['rights_confirmed'] is True
    text = ' '.join(s['text'] for s in p['transcript']['segments']).lower()
    assert 'country' in text and 'americans' in text
    assert p['transcript']['provider'].startswith('faster-whisper')
    assert all(s['words'] for s in p['transcript']['segments'])
    assert len(p['clips']) >= 1
    for c in p['clips']:
        assert 0 <= c['start'] < c['end'] <= p['metadata']['duration']
    clip = p['clips'][0]
    cid = clip['id']
    assert client.get(p['source_url'], headers={'Range': 'bytes=0-99'}).status_code == 206
    assert client.get(p['thumbnail_url']).status_code == 200

    initial_job = client.post(f'/api/clips/{cid}/render').json()
    assert initial_job['id'] == client.post(f'/api/clips/{cid}/render').json()['id']
    p = wait_project(client, pid, 'render')
    original = p['exports'][0]
    assert (original['metadata']['width'], original['metadata']['height']) == (720, 1280)
    assert original['metadata']['video_codec'] == 'h264' and original['metadata']['audio_codec'] == 'aac'
    assert client.get(original['download_url']).content[4:8] == b'ftyp'

    spec = copy.deepcopy(clip['edit'])
    spec['title'] = 'A saved original caption'
    spec['captions'][0]['text'] = 'THIS EDIT IS IN THE MP4'
    spec['captions'][0]['words'] = []
    spec['captions'][0]['start'], spec['captions'][0]['end'] = 0, 3
    spec['caption_preset'], spec['text_color'] = 'boxed', '#FFCC33'
    spec['expected_version'] = clip['version']
    changed = client.put(f'/api/clips/{cid}', json=spec)
    assert changed.status_code == 200, changed.text
    assert changed.json()['version'] == clip['version'] + 1
    assert client.put(f'/api/clips/{cid}', json=spec).status_code == 409
    client.post(f'/api/clips/{cid}/render')
    p = wait_project(client, pid, 'render')
    caption_export = p['exports'][0]
    before_path = worker.project_dir(pid) / 'exports' / f"{original['id']}.mp4"
    after_path = worker.project_dir(pid) / 'exports' / f"{caption_export['id']}.mp4"
    evidence = ROOT / 'tests' / 'artifacts'
    _run([_binary('ffmpeg'), '-v', 'error', '-y', '-ss', '1', '-i', str(before_path), '-frames:v', '1', str(evidence / 'before-caption.png')])
    _run([_binary('ffmpeg'), '-v', 'error', '-y', '-ss', '1', '-i', str(after_path), '-frames:v', '1', str(evidence / 'after-caption.png')])
    import cv2
    a, b = cv2.imread(str(evidence / 'before-caption.png')), cv2.imread(str(evidence / 'after-caption.png'))
    # Same video layout/time; changed text/style must alter pixels in the caption band.
    assert abs(a[900:1200].astype(float) - b[900:1200].astype(float)).mean() > 1

    spec = changed.json()['edit']
    spec.update({'aspect_ratio': '1:1', 'layout': 'manual', 'crop_x': .9, 'start': .5, 'end': 9.5})
    assert client.put(f'/api/clips/{cid}', json=spec).status_code == 200
    client.post(f'/api/clips/{cid}/render')
    p = wait_project(client, pid, 'render')
    square = p['exports'][0]
    assert (square['metadata']['width'], square['metadata']['height']) == (720, 720)
    assert abs(square['metadata']['duration'] - 9) < .2
    # Fresh database connection and HTTP read preserve the actual saved specification.
    reopened = client.get(f'/api/projects/{pid}').json()
    assert reopened['clips'][0]['edit']['crop_x'] == .9
    assert reopened['clips'][0]['edit']['captions'][0]['text'] == 'THIS EDIT IS IN THE MP4'
    from backend.database import engine
    engine.dispose()
    assert client.get(f'/api/projects/{pid}').json()['clips'][0]['edit']['aspect_ratio'] == '1:1'

    # Reanalysis preserves edits and deduplicates unchanged source candidate windows.
    count = len(p['clips'])
    client.post(f'/api/projects/{pid}/analyze', json=p['settings'])
    p = wait_project(client, pid, 'analysis')
    assert len(p['clips']) == count
    assert p['clips'][0]['edit']['title'] == 'A saved original caption'
    summary = {'project_id': pid, 'transcript': p['transcript'], 'initial_export': original, 'caption_export': caption_export,
               'square_export': square, 'persisted_clip': p['clips'][0], 'workspace': str(worker.project_dir(pid))}
    (evidence / 'acceptance.json').write_text(json.dumps(summary, indent=2), encoding='utf-8')


