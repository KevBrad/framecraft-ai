def test_real_running_job_can_cancel_then_delete(client):
    fixture = ROOT / 'tests' / 'artifacts' / 'jfk-source.mp4'
    if not fixture.exists():
        pytest.skip('Authorized speech fixture unavailable.')
    r = client.post('/api/projects', data={'rights_confirmed': 'true'}, files={'file': ('cancel.mp4', fixture.read_bytes())})
    assert r.status_code == 201
    pid, deadline = r.json()['id'], time.monotonic() + 15
    while time.monotonic() < deadline:
        p = client.get(f'/api/projects/{pid}').json()
        if p['jobs'][0]['status'] == 'running':
            break
        time.sleep(.01)
    assert p['jobs'][0]['status'] == 'running'
    j = client.post(f"/api/jobs/{p['jobs'][0]['id']}/cancel").json()
    assert j['status'] == 'cancelled'
    while worker.active_job_id == j['id'] and time.monotonic() < deadline:
        time.sleep(.05)
    assert worker.active_job_id != j['id']
    directory = worker.project_dir(pid)
    assert not list(directory.glob('jobs/*/framecraft-render-*'))
    assert not list(directory.glob('analysis/pending-*'))
    assert client.delete(f'/api/projects/{pid}').status_code == 204
    assert not directory.exists()
